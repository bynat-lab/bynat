"""Generate the typing-only stub for the `df.bynat` pandas accessor.

The stub is derived from `BynatAccessor` by runtime introspection, so shared
function docstrings and signatures remain the source of truth. Run this script
from the repository root after changing an accessor signature; `--check`
verifies that the tracked stub is current.
"""

from __future__ import annotations

import argparse
import inspect
import sys
import types
import typing
from pathlib import Path
from typing import Any

from bynat._accessors.dataframe import BynatAccessor

ROOT = Path(__file__).resolve().parent.parent
STUB_PATH = ROOT / "bynat" / "_accessors" / "dataframe.pyi"
HEADER = (
    "# Generated by tools/gen_accessor_stub.py from runtime introspection of "
    "BynatAccessor.\n"
    "# Do not edit by hand: run `python tools/gen_accessor_stub.py` to "
    "regenerate.\n"
)

# Overloads are deliberately not generated: the union fallback covers the
# inplace copy/mutate split, and combining it with the keyword-only/variadic
# `inplace` slots and the conditional statistics return makes overload sets
# error-prone and hard to keep in sync with the runtime signature.


class _Imports:
    """Collect import statements and emit them in a stable order."""

    def __init__(self) -> None:
        self.modules: dict[str, str] = {}
        self.names: dict[str, set[str]] = {}

    def module(self, module: str, statement: str) -> None:
        """Register a module-level import such as `import pandas as pd`."""
        self.modules[module] = statement

    def name(self, module: str, name: str) -> None:
        """Register a from-import such as `from typing import Any`."""
        self.names.setdefault(module, set()).add(name)

    def render(self) -> str:
        """Return the sorted, grouped import block."""
        groups: dict[int, list[str]] = {0: [], 1: [], 2: []}
        for module, statement in self.modules.items():
            groups[_group(module)].append(statement)
        for module, names in self.names.items():
            joined = ", ".join(sorted(names))
            groups[_group(module)].append(f"from {module} import {joined}")
        blocks = [sorted(groups[group]) for group in (0, 1, 2)]
        return "\n\n".join("\n".join(block) for block in blocks if block)


def _group(module: str) -> int:
    top = module.split(".", 1)[0]
    if top == "bynat":
        return 2
    if top in sys.stdlib_module_names:
        return 0
    return 1


def _require_literal(value: Any) -> None:
    if value is None or isinstance(value, str | int | float | bool):
        return
    if isinstance(value, tuple) and all(_is_literal(item) for item in value):
        return
    raise TypeError(f"Unsupported default {value!r}: only literal defaults are allowed")


def _is_literal(value: Any) -> bool:
    return value is None or isinstance(value, str | int | float | bool)


def _render_default(value: Any) -> str:
    if value is type(None):
        return "None"
    _require_literal(value)
    return repr(value)


def _render_forward_ref(name: str) -> str:
    if name != "BynatAccessor":
        raise ValueError(f"Unsupported forward reference: {name!r}")
    return name


def _render_class(annotation: type, imports: _Imports) -> str:
    module = getattr(annotation, "__module__", "")
    name = annotation.__name__
    if module == "builtins":
        return name
    if module == "pandas" or module.startswith("pandas."):
        imports.module("pandas", "import pandas as pd")
        return f"pd.{name}"
    if module.startswith("numpy.random"):
        imports.module("numpy", "import numpy as np")
        return f"np.random.{name}"
    imports.name(module, name)
    return name


def _render_annotation(annotation: Any, imports: _Imports) -> str:
    if annotation is None or annotation is type(None):
        return "None"
    if annotation is typing.Any:
        imports.name("typing", "Any")
        return "Any"
    if isinstance(annotation, typing.TypeVar):
        imports.module("pandas", "import pandas as pd")
        return "pd.DataFrame"
    if isinstance(annotation, typing.ForwardRef):
        return _render_forward_ref(annotation.__forward_arg__)
    if isinstance(annotation, str):
        return _render_forward_ref(annotation)

    origin = typing.get_origin(annotation)
    arguments = typing.get_args(annotation)
    if origin in (typing.Union, types.UnionType):
        return " | ".join(_render_annotation(arg, imports) for arg in arguments)
    if origin is typing.Literal:
        imports.name("typing", "Literal")
        rendered = ", ".join(repr(arg) for arg in arguments)
        return f"Literal[{rendered}]"
    if origin is not None:
        base = _render_class(origin, imports)
        if not arguments:
            return base
        inner = ", ".join(_render_annotation(arg, imports) for arg in arguments)
        return f"{base}[{inner}]"
    if isinstance(annotation, type):
        return _render_class(annotation, imports)
    raise TypeError(f"Unsupported annotation: {annotation!r} ({type(annotation)!r})")


def _render_parameter(parameter: inspect.Parameter, imports: _Imports) -> str:
    if parameter.kind is inspect.Parameter.VAR_POSITIONAL:
        prefix = "*"
    elif parameter.kind is inspect.Parameter.VAR_KEYWORD:
        prefix = "**"
    else:
        prefix = ""

    annotation = parameter.annotation
    if parameter.name == "inplace":
        if parameter.default is not False:
            raise ValueError(f"inplace default must be False, got {parameter.default!r}")
        annotation = bool

    rendered = parameter.name
    if annotation is not inspect.Parameter.empty:
        rendered += f": {_render_annotation(annotation, imports)}"
    if parameter.default is not inspect.Parameter.empty:
        rendered += f" = {_render_default(parameter.default)}"
    return prefix + rendered


def _render_parameters(signature: inspect.Signature, imports: _Imports) -> str:
    rendered: list[str] = []
    bare_star = False
    for parameter in signature.parameters.values():
        if (
            parameter.kind is inspect.Parameter.KEYWORD_ONLY
            and not bare_star
            and not any(
                item.kind is inspect.Parameter.VAR_POSITIONAL
                for item in signature.parameters.values()
            )
        ):
            rendered.append("*")
            bare_star = True
        rendered.append(_render_parameter(parameter, imports))
    return ", ".join(rendered)


def _render_return(signature: inspect.Signature, imports: _Imports) -> str:
    parameters = signature.parameters
    if "inplace" in parameters:
        if "get_hierarchical_stats" in parameters:
            imports.name("typing", "Any")
            return "Any"
        imports.module("pandas", "import pandas as pd")
        return "pd.DataFrame | None"
    return _render_annotation(signature.return_annotation, imports)


def _render_docstring(doc: str | None, indent: int) -> str:
    if not doc:
        return ""
    cleaned = inspect.cleandoc(doc)
    if '"""' in cleaned:
        raise ValueError("Docstring contains triple quotes and cannot be rendered")
    if cleaned.endswith("\\"):
        raise ValueError("Docstring ends with a backslash and cannot be rendered")
    pad = " " * indent
    lines = [f"{pad}r\"\"\""]
    lines.extend(f"{pad}{line}" if line else "" for line in cleaned.splitlines())
    lines.append(f"{pad}\"\"\"")
    return "\n".join(lines)


def render_stub(cls: type) -> str:
    """Render the `.pyi` text for `cls` and its public members."""
    imports = _Imports()
    imports.module("pandas", "import pandas as pd")
    members: list[tuple[str, inspect.Signature, str | None, bool]] = []
    for name, member in vars(cls).items():
        if name.startswith("_") and name != "__init__":
            continue
        is_property = isinstance(member, property)
        target = member.fget if is_property else member
        members.append((name, inspect.signature(target), inspect.getdoc(target), is_property))

    rendered_members: list[str] = []
    for name, signature, doc, is_property in members:
        parameters = _render_parameters(signature, imports)
        returns = _render_return(signature, imports)
        decorator = "    @property\n" if is_property else ""
        rendered_members.append(
            f"{decorator}    def {name}({parameters}) -> {returns}:\n"
            f"{_render_docstring(doc, 8)}\n"
            "        ..."
        )

    class_block = (
        "class BynatAccessor:\n"
        f"{_render_docstring(inspect.getdoc(cls), 4)}\n\n"
        # `_obj` is bound in __init__, not on the class, so vars(cls) cannot see
        # it. The binding factories reference it and must type-check against
        # the stub; no private API is added at runtime by declaring it here.
        "    _obj: pd.DataFrame\n\n"
        + "\n\n".join(rendered_members)
    )
    parts = [HEADER.rstrip("\n"), _import_block(imports), "__all__ = ['BynatAccessor']", class_block]
    return "\n\n".join(parts) + "\n"


def _import_block(imports: _Imports) -> str:
    return imports.render()


def _display_path(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def main(argv: list[str] | None = None) -> int:
    """Generate the stub, or check that the tracked stub matches it."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the tracked stub differs from freshly generated text",
    )
    arguments = parser.parse_args(argv)
    generated = render_stub(BynatAccessor)

    if arguments.check:
        tracked = STUB_PATH.read_text(encoding="utf-8").replace("\r\n", "\n")
        if tracked == generated:
            print(f"{_display_path(STUB_PATH)} is up to date")
            return 0
        print(
            f"{_display_path(STUB_PATH)} is out of date: "
            "run `python tools/gen_accessor_stub.py` to regenerate it",
            file=sys.stderr,
        )
        return 1

    with STUB_PATH.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(generated)
    print(f"Wrote {_display_path(STUB_PATH)} ({len(generated.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
