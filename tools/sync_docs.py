"""
Make bynat's shared docstrings and signatures visible to static analysis.

The functions in `columns`, `text`, `stats`, `profile`, `io`, and `enrich` are
the single source of truth for docstrings. Two things are derived from them:

1. `BaseData` methods decorated with `@_shares_doc(module.func)` get the
   shared docstring written as a literal docstring, so editors and type
   checkers (which never run the decorator) can show it on hover. The
   decorator still assigns `__doc__` at runtime.
2. `bynat/cleaning/accessor.pyi` is generated from `accessor.py`: the methods
   created by `_frame_method` / `_cached_frame_method` become real
   signatures (without the frame and `cache_manager` parameters) carrying the
   shared docstring.

Usage:
    python tools/sync_docs.py          # rewrite base.py and accessor.pyi
    python tools/sync_docs.py --check  # exit 1 if anything is out of date
"""

from __future__ import annotations

import argparse
import ast
import copy
import importlib
import inspect
import sys
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLEANING = ROOT / "bynat" / "cleaning"
BASE_PATH = CLEANING / "base.py"
ACCESSOR_PATH = CLEANING / "accessor.py"
STUB_PATH = CLEANING / "accessor.pyi"

BASE_MODULE = "bynat.cleaning.base"
ACCESSOR_MODULE = "bynat.cleaning.accessor"
METHOD_FACTORIES = ("_frame_method", "_cached_frame_method")
METHOD_INDENT = " " * 8

STUB_HEADER = (
    "# This file is generated by tools/sync_docs.py from accessor.py and the\n"
    "# shared implementation functions. Do not edit it by hand: run\n"
    "# `python tools/sync_docs.py` instead.\n"
)


# --------------------------------------------------------------------------
# Small helpers
# --------------------------------------------------------------------------

def _read(path: Path) -> str:
    with open(path, encoding = "utf-8", newline = "") as handle:
        return handle.read()


def _write(path: Path, text: str) -> None:
    with open(path, "w", encoding = "utf-8", newline = "") as handle:
        handle.write(text)


def _newline_of(text: str) -> str:
    return "\r\n" if "\r\n" in text else "\n"


def _shared_doc(func: object) -> str:
    """The docstring exactly as `_shares_doc` and `inspect.getdoc` see it."""
    return inspect.cleandoc(getattr(func, "__doc__", None) or "")


def _docstring_literal(doc: str, indent: str) -> list[str]:
    """Render `doc` as a triple-quoted literal whose cleaned value equals `doc`."""
    if '"""' in doc:
        raise ValueError('docstrings containing """ are not supported')

    prefix = ""
    if "\\" in doc:
        if doc.endswith("\\"):
            raise ValueError("docstrings ending with a backslash are not supported")
        prefix = "r"

    lines = [f'{indent}{prefix}"""']
    lines.extend(f"{indent}{line}" if line.strip() else "" for line in doc.splitlines())
    lines.append(f'{indent}"""')
    return lines


def _resolve(module_name: str, dotted: str) -> object:
    """Resolve `mod.func` the way the class body of `module_name` sees it."""
    module = importlib.import_module(module_name)
    obj: object = module
    for part in dotted.split("."):
        obj = getattr(obj, part)
    return obj


def _dotted(node: ast.expr) -> str:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return f"{_dotted(node.value)}.{node.attr}"
    raise ValueError(f"unsupported reference: {ast.unparse(node)}")


def _class_def(tree: ast.Module, name: str) -> ast.ClassDef:
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == name:
            return node
    raise LookupError(f"class {name} not found")


# --------------------------------------------------------------------------
# 1. Literal docstrings on BaseData
# --------------------------------------------------------------------------

@dataclass
class SharedDocMethod:
    name: str
    source: str            # e.g. "stats.fill_missing"
    node: ast.FunctionDef


def iter_shared_doc_methods(tree: ast.Module) -> Iterator[SharedDocMethod]:
    """Yield every `BaseData` method decorated with `@_shares_doc(...)`."""
    for node in _class_def(tree, "BaseData").body:
        if not isinstance(node, ast.FunctionDef):
            continue
        for decorator in node.decorator_list:
            if (
                isinstance(decorator, ast.Call)
                and isinstance(decorator.func, ast.Name)
                and decorator.func.id == "_shares_doc"
            ):
                yield SharedDocMethod(node.name, _dotted(decorator.args[0]), node)


def render_base(source: str) -> str:
    """Return `base.py` with every shared docstring written as a literal."""
    newline = _newline_of(source)
    lines = source.splitlines()
    tree = ast.parse(source)

    edits: list[tuple[int, int, list[str]]] = []
    for method in iter_shared_doc_methods(tree):
        doc = _shared_doc(_resolve(BASE_MODULE, method.source))
        literal = _docstring_literal(doc, METHOD_INDENT)
        first = method.node.body[0]
        has_doc = (
            isinstance(first, ast.Expr)
            and isinstance(first.value, ast.Constant)
            and isinstance(first.value.value, str)
        )
        if has_doc:
            assert first.end_lineno is not None
            edits.append((first.lineno - 1, first.end_lineno, literal))
        else:
            edits.append((first.lineno - 1, first.lineno - 1, literal))

    for start, end, replacement in sorted(edits, reverse = True):
        lines[start:end] = replacement

    trailing = newline if source.endswith(("\n", "\r")) else ""
    return newline.join(lines) + trailing


def check_base_docstrings(source: str) -> list[str]:
    """Describe every `BaseData` method whose literal docstring is stale."""
    problems = []
    for method in iter_shared_doc_methods(ast.parse(source)):
        expected = _shared_doc(_resolve(BASE_MODULE, method.source))
        actual = ast.get_docstring(method.node, clean = True)
        if actual is None:
            problems.append(f"BaseData.{method.name} has no literal docstring (source: {method.source})")
        elif actual != expected:
            problems.append(f"BaseData.{method.name} docstring differs from {method.source}.__doc__")
    return problems


