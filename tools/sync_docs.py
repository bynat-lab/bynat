# Entry point
# --------------------------------------------------------------------------

def check() -> list[str]:
    """Return a description of every out-of-date generated artifact."""
    problems = check_base_docstrings(_read(BASE_PATH))
    if not STUB_PATH.exists():
        problems.append(f"{STUB_PATH.relative_to(ROOT)} is missing")
    elif _read(STUB_PATH).replace("\r\n", "\n") != render_stub():
        problems.append(f"{STUB_PATH.relative_to(ROOT)} is out of date")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description = __doc__.splitlines()[1] if __doc__ else None)
    parser.add_argument("--check", action = "store_true", help = "only report drift; exit 1 if any")
    options = parser.parse_args(argv)

    if options.check:
        problems = check()
        for problem in problems:
            print(f"out of sync: {problem}", file = sys.stderr)
        if problems:
            print("Run `python tools/sync_docs.py` to regenerate.", file = sys.stderr)
            return 1
        print("Docstrings and accessor.pyi are in sync.")
        return 0

    base_source = _read(BASE_PATH)
    new_base = render_base(base_source)
    if new_base != base_source:
        _write(BASE_PATH, new_base)
        print(f"updated {BASE_PATH.relative_to(ROOT)}")

    stub = render_stub()
    if not STUB_PATH.exists() or _read(STUB_PATH) != stub:
        _write(STUB_PATH, stub)
        print(f"updated {STUB_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT))
    raise SystemExit(main())
