class _NameCollector(ast.NodeVisitor):
    def __init__(self, annotation: bool) -> None:
        self.names: set[str] = set()
        self.annotation = annotation

    def visit_Name(self, node: ast.Name) -> None:
        self.names.add(node.id)

    def visit_Constant(self, node: ast.Constant) -> None:
        # String annotations ("BynatAccessor") reference names too; string
        # defaults ("_") do not.
        if self.annotation and isinstance(node.value, str) and node.value.isidentifier():
            self.names.add(node.value)


def _referenced_names(node: ast.AST) -> set[str]:
    """Names a signature, decorator, or annotation needs to be importable."""
    if isinstance(node, ast.arguments):
        names: set[str] = set()
        every_arg = [*node.posonlyargs, *node.args, *node.kwonlyargs]
        every_arg += [arg for arg in (node.vararg, node.kwarg) if arg is not None]
        for arg in every_arg:
            if arg.annotation is not None:
                names |= _referenced_names(arg.annotation)
        for default in [*node.defaults, *node.kw_defaults]:
            if default is not None:
                collector = _NameCollector(annotation = False)
                collector.visit(default)
                names |= collector.names
        return names
    collector = _NameCollector(annotation = True)
    collector.visit(node)
    return collector.names


class _FrameTRewriter(ast.NodeTransformer):
    """The accessor always wraps a plain `pandas.DataFrame`."""

    def visit_Name(self, node: ast.Name) -> ast.AST:
        if node.id == "FrameT":
            return ast.copy_location(
                ast.Attribute(ast.Name("pd", ast.Load()), "DataFrame", ast.Load()), node
            )
        return node


def _module_path(module_name: str) -> Path:
    module = importlib.import_module(module_name)
    assert module.__file__ is not None
    return Path(module.__file__)


def _absolute(module_name: str, level: int, target: str | None) -> str:
    if not level:
        return target or ""
    package = module_name.split(".")
    is_package = _module_path(module_name).name == "__init__.py"
    base = package if is_package else package[:-1]
    base = base[: len(base) - (level - 1)]
    return ".".join(base + ([target] if target else []))


def _module_bindings(module_name: str) -> dict[str, str]:
    """Map each top-level name of a module to the import line that binds it."""
    tree = ast.parse(_read(_module_path(module_name)))
    bindings: dict[str, str] = {}
    for node in tree.body:
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.asname:
                    bindings[alias.asname] = f"import {alias.name} as {alias.asname}"
                else:
                    top = alias.name.split(".")[0]
                    bindings[top] = f"import {top}"
        elif isinstance(node, ast.ImportFrom):
            source = _absolute(module_name, node.level, node.module)
            for alias in node.names:
                bound = alias.asname or alias.name
                suffix = f" as {alias.asname}" if alias.asname else ""
                bindings[bound] = f"from {source} import {alias.name}{suffix}"
        elif isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            bindings[node.name] = f"from {module_name} import {node.name}"
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for target in targets:
                if isinstance(target, ast.Name):
                    bindings[target.id] = f"from {module_name} import {target.id}"
    return bindings


_BUILTINS = set(dir(__import__("builtins")))


def _import_sections(imports: set[str]) -> list[list[str]]:
    """Group and merge import lines the way ruff's isort rules expect."""
    sections: dict[int, tuple[set[str], dict[str, set[str]]]] = {}
    for line in imports:
        module = line.split()[1]
        top = module.split(".")[0]
        section = 2 if top == "bynat" else 0 if top in sys.stdlib_module_names else 1
        plain, froms = sections.setdefault(section, (set(), {}))
        if line.startswith("import "):
            plain.add(line)
        else:
            froms.setdefault(module, set()).add(line.split(" import ", 1)[1])

    def name_key(name: str) -> tuple[int, str]:
        bare = name.split(" as ")[0]
        kind = 0 if bare.isupper() and len(bare) > 1 else 1 if bare[:1].isupper() else 2
        return kind, bare

    rendered = []
    for section in sorted(sections):
        plain, froms = sections[section]
        lines = sorted(plain, key = lambda line: line.split()[1])
        for module in sorted(froms):
            names = ", ".join(sorted(froms[module], key = name_key))
            lines.append(f"from {module} import {names}")
        rendered.append(lines)
    return rendered


def _stub_function(
    func: object,
    name: str,
    drop_cache_manager: bool,
) -> tuple[ast.FunctionDef, str]:
    """Build the stub method for one shared function, and its source module."""
    module_name = func.__module__  # type: ignore[attr-defined]
    tree = ast.parse(_read(_module_path(module_name)))
    func_name = func.__name__  # type: ignore[attr-defined]
    original = next(
        node for node in tree.body
        if isinstance(node, ast.FunctionDef) and node.name == func_name
    )

    args = copy.deepcopy(original.args)
    positional = args.posonlyargs + args.args
    first = positional[0]
    if first in args.posonlyargs:
        args.posonlyargs.remove(first)
    else:
        args.args.remove(first)
    args.posonlyargs.insert(0, ast.arg("self")) if args.posonlyargs else args.args.insert(0, ast.arg("self"))

    if drop_cache_manager:
        for index, arg in enumerate(args.kwonlyargs):
            if arg.arg == "cache_manager":
                del args.kwonlyargs[index]
                del args.kw_defaults[index]
                break
        else:
            raise LookupError(f"{module_name}.{func_name} has no keyword-only cache_manager")

    returns = copy.deepcopy(original.returns)
    node = ast.FunctionDef(
        name = name,
        args = args,
        body = [
            ast.Expr(ast.Constant(_shared_doc(func))),
            ast.Expr(ast.Constant(...)),
        ],
        decorator_list = [],
        returns = returns,
        type_comment = None,
        type_params = [],
    )
    node = _FrameTRewriter().visit(node)
    return ast.fix_missing_locations(node), module_name


class _AnnotationUnquoter(ast.NodeTransformer):
    """Replace string literal annotations (e.g. 'BynatAccessor') with AST nodes."""

    def visit_Constant(self, node: ast.Constant) -> ast.AST:
        if isinstance(node.value, str) and node.value.isidentifier():
            return ast.copy_location(ast.Name(id = node.value, ctx = ast.Load()), node)
        return node


def _clean_stub_node(node: ast.FunctionDef) -> ast.FunctionDef:
    """Strip quotes from annotations so .pyi complies with UP037."""
    cleaned = copy.deepcopy(node)
    unquoter = _AnnotationUnquoter()
    if cleaned.returns is not None:
        cleaned.returns = unquoter.visit(cleaned.returns)
    all_args = [*cleaned.args.posonlyargs, *cleaned.args.args, *cleaned.args.kwonlyargs]
    if cleaned.args.vararg:
        all_args.append(cleaned.args.vararg)
    if cleaned.args.kwarg:
        all_args.append(cleaned.args.kwarg)
    for arg in all_args:
        if arg.annotation is not None:
            arg.annotation = unquoter.visit(arg.annotation)
    return ast.fix_missing_locations(cleaned)


def _render_function(node: ast.FunctionDef, indent: str) -> list[str]:
    """Unparse a stub function, writing its docstring in readable form."""
    cleaned = _clean_stub_node(node)
    doc = cleaned.body[0].value.value  # type: ignore[attr-defined]
    bare = copy.deepcopy(cleaned)
    bare.body = [ast.Expr(ast.Constant(...))]
    header = ast.unparse(bare).splitlines()[0]  # "def name(...) -> T:"
    assert header.endswith(":"), header
    lines = [indent + header]
    if doc:
        lines.extend(_docstring_literal(doc, indent + "    "))
    lines.append(indent + "    ...")
    return lines


def render_stub() -> str:
    """Generate the full text of `accessor.pyi`."""
    accessor_source = _read(ACCESSOR_PATH)
    tree = ast.parse(accessor_source)
    cls = _class_def(tree, "BynatAccessor")
    accessor_bindings = _module_bindings(ACCESSOR_MODULE)

    imports: set[str] = set()
    needed: list[tuple[str, str]] = []  # (name, module whose bindings apply)

    def need(node: ast.AST, module_name: str) -> None:
        for found in sorted(_referenced_names(node)):
            needed.append((found, module_name))

    body: list[str] = []
    for node in cls.body:
        if (
            isinstance(node, ast.Expr)
            and isinstance(node.value, ast.Constant)
            and isinstance(node.value.value, str)
        ):
            body.extend(_docstring_literal(inspect.cleandoc(node.value.value), "    "))
            body.append("")
        elif isinstance(node, ast.FunctionDef):
            # Hand-written methods: keep signature, decorators, and docstring.
            stub = copy.deepcopy(node)
            doc = ast.get_docstring(node, clean = True)
            stub.body = [ast.Expr(ast.Constant(doc or "")), ast.Expr(ast.Constant(...))]
            for decorator in stub.decorator_list:
                need(decorator, ACCESSOR_MODULE)
            need(stub.args, ACCESSOR_MODULE)
            if stub.returns is not None:
                need(stub.returns, ACCESSOR_MODULE)
            decorators = [f"    @{ast.unparse(d)}" for d in stub.decorator_list]
            stub.decorator_list = []
            body.extend(decorators + _render_function(stub, "    "))
            body.append("")
        elif (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and isinstance(node.value, ast.Call)
            and isinstance(node.value.func, ast.Name)
            and node.value.func.id in METHOD_FACTORIES
        ):
            name = node.targets[0].id
            runtime_cls = importlib.import_module(ACCESSOR_MODULE).BynatAccessor
            func = vars(runtime_cls)[name].__wrapped__
            stub, module_name = _stub_function(
                func, name, drop_cache_manager = node.value.func.id == "_cached_frame_method"
            )
            need(stub.args, module_name)
            if stub.returns is not None:
                need(stub.returns, module_name)
            body.extend(_render_function(stub, "    "))
            body.append("")
        else:
            raise ValueError(
                f"unsupported statement in BynatAccessor at line {node.lineno}: "
                f"{ast.unparse(node).splitlines()[0]}"
            )

    defined_here = {"BynatAccessor", "self"}
    bindings_cache: dict[str, dict[str, str]] = {ACCESSOR_MODULE: accessor_bindings}
    for found, module_name in needed:
        if found in defined_here or found in _BUILTINS:
            continue
        bindings = bindings_cache.setdefault(module_name, _module_bindings(module_name))
        if found == "pd" and found not in bindings:
            # Introduced by `_FrameTRewriter` in modules that only use `FrameT`.
            imports.add("import pandas as pd")
            continue
        if found not in bindings:
            raise LookupError(f"cannot resolve name {found!r} used by {module_name}")
        imports.add(bindings[found])

    out = STUB_HEADER.rstrip("\n").split("\n")
    out.append("")
    for group in _import_sections(imports):
        out.extend(group)
        out.append("")
    out.append("__all__ = ['BynatAccessor']")
    out.append("")
    out.append("class BynatAccessor:")
    while body and body[-1] == "":
        body.pop()
    out.extend(body)
    return "\n".join(out) + "\n"


